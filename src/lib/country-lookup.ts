export function normalizeCountryKey(value: string): string {
  return value
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

const NAME_TO_ID: Record<string, string> = {};

for (const [id, name] of Object.entries(COUNTRY_NAMES)) {
  NAME_TO_ID[normalizeCountryKey(name)] = id;
  NAME_TO_ID[id] = id;
}

for (const [id, iso2, iso3] of ISO_ROWS) {
  NAME_TO_ID[id] = id;
  NAME_TO_ID[iso2.toLowerCase()] = id;
  NAME_TO_ID[iso3.toLowerCase()] = id;
}

for (const [alias, id] of Object.entries(ALIASES)) {
  NAME_TO_ID[alias] = id;
}

export function resolveCountryId(raw: string): string | null {
  const trimmed = raw.trim();
  if (!trimmed) return null;
  if (/^\d{1,3}$/.test(trimmed)) {
    const id = trimmed.padStart(3, "0");
    return COUNTRY_NAMES[id] ? id : NAME_TO_ID[id] ?? null;
  }
  const key = normalizeCountryKey(trimmed);
  const id = NAME_TO_ID[key];
  if (id && COUNTRY_NAMES[id]) return id;
  if (id) return id;
  return null;
}
